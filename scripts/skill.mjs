import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { checkIndex, loadIcons, root } from "./icons.mjs";

export const referenceFile = path.join(root, "skills/coolicons/references/icons.md");

export function skillReference() {
  const { manifest, icons } = loadIcons();
  const index = checkIndex(manifest);
  const { version } = JSON.parse(readFileSync(path.join(root, "packages/react/package.json"), "utf8"));
  const keywords = new Map(index.icons.map((icon) => [icon.name, icon.keywords]));
  const component = (icon) => (Object.hasOwn(index.clashes, icon.name) ? `${icon.component}Icon` : icon.component);
  const line = (icon) => {
    const tags = keywords.get(icon.name).join(", ");
    const alias = icon.aliasOf ? `same drawing as ${icon.aliasOf}` : "";
    return `- ${icon.name} (${component(icon)})${[alias, tags].filter(Boolean).length ? `: ${[alias, tags].filter(Boolean).join(", ")}` : ""}`;
  };
  const categories = [...new Set(icons.map((icon) => icon.category))];
  const sections = categories.map((category) => `## ${category}\n\n${icons.filter((icon) => icon.category === category).map(line).join("\n")}`);
  return `# coolicons icons

Every icon of coolicons ${version}, ${icons.length} in total, grouped by category. Each line has the icon name, the component name for React and Vue, and search tags. Generated by \`pnpm skill\` from \`icons/\`, do not edit by hand.

${sections.join("\n\n")}
`;
}

if (import.meta.filename === path.resolve(process.argv[1] ?? "")) {
  writeFileSync(referenceFile, skillReference());
  console.log(`Wrote ${path.relative(root, referenceFile)}`);
}
